export const lucideIconsBundle = LUCIDE_ICON_NODES

function kebabToPascal(name) {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
}

/**
 * @param {string} name - Lucide kebab-case name (e.g. book-open)
 * @param {string} [className]
 * @returns {string} SVG HTML
 */
export function renderLucideIcon(name, className = "") {
  const iconNode = LUCIDE_ICON_NODES[kebabToPascal(name)]
  if (!iconNode) return ""

  if (typeof document !== "undefined") {
    const svg = createElement(iconNode, {
      class: className,
      "stroke-width": STROKE_WIDTH,
      "aria-hidden": "true",
    })
    return svg.outerHTML
  }

  return ""
}
